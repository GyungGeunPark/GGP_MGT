T = np.array(data["transform_applied"], dtype=np.float64)
unit_scale = float(data.get("output_unit_scale", 1.0))

# ====== 옵션 ======
# output_unit_scale=1000 이면 mm 데이터로 보고 /1000 해서 m로 만든다고 가정
APPLY_UNIT_SCALE_DIV = True   # True: xyz /= unit_scale  (mm->m), False: 그대로
NORMALIZE_NORMALS = True      # normals 정규화 여부
ARROW_FACTOR = 0.08           # 화살표 길이(단위 m 가정). mm 그대로면 예: 80 정도

plotter = pv.Plotter()
plotter.add_axes()

for li, line in enumerate(data["lines"]):
    arr = np.asarray(line, dtype=np.float64)
    pts = arr[:, 0:3].copy()
    nrm = arr[:, 3:6].copy()

    # (1) 단위 스케일 반영
    if APPLY_UNIT_SCALE_DIV and unit_scale != 0:
        pts /= unit_scale

    # (2) transform_applied 적용 (xyz에만)
    pts_h = np.c_[pts, np.ones((pts.shape[0], 1), dtype=np.float64)]
    pts_tf = (T @ pts_h.T).T[:, 0:3]

    # (3) normals 처리
    if NORMALIZE_NORMALS:
        denom = np.linalg.norm(nrm, axis=1, keepdims=True)
        denom = np.where(denom < 1e-12, 1.0, denom)
        nrm = nrm / denom

    # normals도 회전은 적용(translation 제외)하려면 아래처럼:
    R = T[0:3, 0:3]
    nrm_tf = (R @ nrm.T).T
    if NORMALIZE_NORMALS:
        denom = np.linalg.norm(nrm_tf, axis=1, keepdims=True)
        denom = np.where(denom < 1e-12, 1.0, denom)
        nrm_tf = nrm_tf / denom

    # (4) 라인(폴리라인) + 점 + 화살표
    poly = pv.PolyData(pts_tf)
    poly["normals"] = nrm_tf

    # 폴리라인 연결 (0-1-2-...-N-1)
    n = pts_tf.shape[0]
    cells = np.hstack(([n], np.arange(n, dtype=np.int64)))
    poly.lines = cells

    arrows = poly.glyph(orient="normals", scale=False, factor=ARROW_FACTOR)

    # 라인/점/화살표 추가
    plotter.add_mesh(poly, line_width=3)  # 라인
    plotter.add_mesh(poly, point_size=8, render_points_as_spheres=True)  # 점
    plotter.add_mesh(arrows)  # 화살표

# 보기 좋게 카메라
plotter.show_grid()
plotter.show()
